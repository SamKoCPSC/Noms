#!/usr/bin/env python3
"""Build Chef Penguini's standalone SVGs and browser clip registry."""

import argparse
import json
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape


ROOT = Path(__file__).resolve().parents[1] / "assets/brand/penguini"
BASE_STYLE = """
.penguin,.head,.flipper,.shadow,.eyes-open,.eyes-happy,.blink,.lower-beak,.front-arm,.front-flipper,.kiss-spark,.back-arm,.left-flipper{transform:none;opacity:1}
.penguin{transform-origin:580px 990px}.head{transform-origin:350px 740px}
.flipper,.front-flipper{transform-origin:1305px 610px;transform:rotate(88deg)}
.shadow{transform-origin:580px 1000px;opacity:.13}.blink{transform-origin:350px 550px}
.lower-beak{transform-origin:355px 610px;transform:scaleY(.45)}
.eyes-happy,.front-arm,.kiss-spark{opacity:0}.kiss-spark{transform-origin:1020px 330px}
"""


def render_svg(rig, title, description, style):
    svg = re.sub(r'(<title id="title">).*?(</title>)',
                 lambda m: m[1] + escape(title) + m[2], rig)
    svg = re.sub(r'(<desc id="desc">).*?(</desc>)',
                 lambda m: m[1] + escape(description) + m[2], svg)
    return svg.replace("<defs>", "<style>" + style + "</style><defs>")


def build():
    clips = json.loads((ROOT / "source/clips.json").read_text())
    rig = (ROOT / "source/rig.svg").read_text()
    outputs = {
        ROOT / "clips.js": "// Generated by scripts/build-mascot-assets.py; edit source/clips.json.\n"
        + "window.PenguiniClips = " + json.dumps(clips, separators=(",", ":")) + ";\n",
        ROOT / "still.svg": render_svg(
            rig, "Chef Penguini", "A smiling penguin in a chef hat and terracotta apron.", BASE_STYLE),
    }
    for clip_id, clip in clips.items():
        # Procedural meshes cannot be represented by transform/opacity CSS.
        # Their individual preview uses the inline player, not a partial SVG.
        if clip.get("renderer"):
            continue
        css = BASE_STYLE
        for index, track in enumerate(clip["tracks"]):
            frames = []
            for frame in track["keyframes"]:
                properties = [f"{key}:{frame[key]}" for key in ("transform", "opacity") if key in frame]
                properties.append("animation-timing-function:" + frame.get("easing", "linear"))
                frames.append(f"{frame.get('offset', 0) * 100:.8f}%" + "{" + ";".join(properties) + "}")
            css += f"@keyframes gesture{index}" + "{" + "".join(frames) + "}"
            duration = track.get("durationMs", clip["durationMs"])
            repeat = "infinite" if clip_id == "idle" else "1"
            css += track["selector"] + "{animation:gesture" + str(index) + f" {duration}ms "
            css += track.get("easing", "linear") + f" {repeat} both" + "}"
        css += "@media(prefers-reduced-motion:reduce){svg *{animation:none!important}}"
        description = (
            "Chef Penguini gently sways and blinks."
            if clip_id == "idle" else f"Chef Penguini performs {clip['label'].lower()} and returns to rest."
        )
        outputs[ROOT / "animations" / f"{clip_id}.svg"] = render_svg(
            rig, "Chef Penguini — " + clip["label"], description, css)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated assets are out of date.")
    args = parser.parse_args()
    stale = []
    outputs = build()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Out-of-date mascot assets: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Built'} {len(outputs)} mascot assets.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
